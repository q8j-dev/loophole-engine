from loophole import Game

game = Game("Helper Test")

lab = game.level("Lab")
lab.room(0, 0, 0, 12, 6, 14)
lab.room(5, 0, -6, 7, 3, 0)
lab.spawn(6, 0, 12, yaw=0)
lab.strip(3, 5.95, 1, 3, 5.95, 13, power=26)
lab.light(9, 5, 9, name="lamp1")
