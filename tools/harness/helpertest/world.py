lab.button("button", 3, 0, 4, opens="door")
lab.door("door", 6, 0, -0.6, facing="+z", width=2, height=3)
lab.pickup("apple1", "apple", 6, 0.4, 9, scale=3)
lab.object("enemy", "rat", 9, 0, 1, scale=6, solid=False)
lab.goal(5, 0, -5.5, 7, 3, -3.5)
lab.checkpoint(9, 0, 9.5, 11, 3, 11.5)
lab.hazard(0.5, 0, 12.5, 2, 1, 13.5)
intro = lab.cutscene("intro", play_at_start=True)
intro.camera(0, (6, 5, 13), turn=0, tilt=-15)
intro.camera(3, (2, 3, 3), turn=-50, tilt=-12)
intro.subtitle(0.5, "Welcome to the lab", duration=2)
intro.move(1, "cube", (6, 0.34, 6), over=1.5)
intro.open(2, "door")
intro.sound(2, "door_open")

